-- The Meridian tables in Snowflake, with explicit types.
CREATE OR REPLACE TABLE DIM_COUNTRY  (COUNTRY_ID INTEGER PRIMARY KEY, COUNTRY_NAME VARCHAR(50));
CREATE OR REPLACE TABLE DIM_CATEGORY (CATEGORY_ID INTEGER PRIMARY KEY, CATEGORY_NAME VARCHAR(50));
CREATE OR REPLACE TABLE DIM_CUSTOMER (CUSTOMER_ID INTEGER PRIMARY KEY, FIRST_NAME VARCHAR(50),
    LAST_NAME VARCHAR(50), EMAIL VARCHAR(100), COUNTRY_ID INTEGER, SIGNUP_DATE DATE);
CREATE OR REPLACE TABLE DIM_PRODUCT  (PRODUCT_ID INTEGER PRIMARY KEY, PRODUCT_NAME VARCHAR(100),
    CATEGORY_ID INTEGER, UNIT_PRICE NUMBER(8,2));
CREATE OR REPLACE TABLE FACT_ORDERS  (ORDER_ID INTEGER PRIMARY KEY, CUSTOMER_ID INTEGER,
    PRODUCT_ID INTEGER, ORDER_DATE DATE, QUANTITY INTEGER, UNIT_PRICE NUMBER(8,2),
    TOTAL_AMOUNT NUMBER(10,2), STATUS VARCHAR(20));
